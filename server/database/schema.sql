CREATE DATABASE IF NOT EXISTS subscription_management CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE subscription_management;
CREATE TABLE IF NOT EXISTS roles (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(50) NOT NULL UNIQUE, permissions JSON NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS users (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(120) NOT NULL, email VARCHAR(190) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NULL, role_id INT UNSIGNED NULL, status VARCHAR(20) NOT NULL DEFAULT 'active',
 refresh_token VARCHAR(128) NULL, last_login_at DATETIME NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CONSTRAINT fk_users_role FOREIGN KEY(role_id) REFERENCES roles(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS customers (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id INT UNSIGNED NULL, name VARCHAR(160) NOT NULL,
 company VARCHAR(160) NULL, email VARCHAR(190) NOT NULL UNIQUE, phone VARCHAR(40) NULL, tax_id VARCHAR(80) NULL,
 billing_address TEXT NULL, shipping_address TEXT NULL, status VARCHAR(20) NOT NULL DEFAULT 'active',
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CONSTRAINT fk_customers_user FOREIGN KEY(user_id) REFERENCES users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS categories (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(160) NOT NULL, parent_id INT UNSIGNED NULL, status VARCHAR(20) NOT NULL DEFAULT 'active',
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CONSTRAINT fk_categories_parent FOREIGN KEY(parent_id) REFERENCES categories(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS products (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, category_id INT UNSIGNED NULL, name VARCHAR(160) NOT NULL, product_type VARCHAR(40) NOT NULL DEFAULT 'subscription',
 price DECIMAL(15,2) NOT NULL DEFAULT 0, cost_price DECIMAL(15,2) NOT NULL DEFAULT 0, notes TEXT NULL, status VARCHAR(20) NOT NULL DEFAULT 'active',
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CONSTRAINT fk_products_category FOREIGN KEY(category_id) REFERENCES categories(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS product_variants (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, product_id INT UNSIGNED NOT NULL, name VARCHAR(160) NOT NULL, attributes JSON NULL,
 price_adjustment DECIMAL(15,2) NOT NULL DEFAULT 0, status VARCHAR(20) DEFAULT 'active',
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CONSTRAINT fk_variant_product FOREIGN KEY(product_id) REFERENCES products(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS subscription_plans (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, product_id INT UNSIGNED NULL, name VARCHAR(160) NOT NULL, billing_cycle VARCHAR(30) NOT NULL DEFAULT 'monthly',
 billing_interval INT UNSIGNED NOT NULL DEFAULT 1, price DECIMAL(15,2) NOT NULL, trial_days INT UNSIGNED NOT NULL DEFAULT 0, status VARCHAR(20) DEFAULT 'active',
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CONSTRAINT fk_plans_product FOREIGN KEY(product_id) REFERENCES products(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS quotations (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, number VARCHAR(60) NOT NULL UNIQUE, customer_id INT UNSIGNED NOT NULL, subtotal DECIMAL(15,2) DEFAULT 0,
 tax_amount DECIMAL(15,2) DEFAULT 0, discount_amount DECIMAL(15,2) DEFAULT 0, total DECIMAL(15,2) DEFAULT 0, status VARCHAR(30) DEFAULT 'draft', valid_until DATE NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CONSTRAINT fk_quotes_customer FOREIGN KEY(customer_id) REFERENCES customers(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS subscriptions (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, number VARCHAR(60) NOT NULL UNIQUE, customer_id INT UNSIGNED NOT NULL, plan_id INT UNSIGNED NULL,
 status VARCHAR(30) NOT NULL DEFAULT 'active', unit_price DECIMAL(15,2) NOT NULL DEFAULT 0, quantity INT UNSIGNED NOT NULL DEFAULT 1,
 starts_at DATE NULL, next_billing_at DATE NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CONSTRAINT fk_sub_customer FOREIGN KEY(customer_id) REFERENCES customers(id), CONSTRAINT fk_sub_plan FOREIGN KEY(plan_id) REFERENCES subscription_plans(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS billing_runs (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, period_start DATE NOT NULL, period_end DATE NOT NULL, status VARCHAR(30) NOT NULL DEFAULT 'pending',
 invoices_generated INT UNSIGNED NOT NULL DEFAULT 0, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS invoices (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, number VARCHAR(60) NOT NULL UNIQUE, customer_id INT UNSIGNED NOT NULL, subscription_id INT UNSIGNED NULL,
 subtotal DECIMAL(15,2) DEFAULT 0, tax_amount DECIMAL(15,2) DEFAULT 0, discount_amount DECIMAL(15,2) DEFAULT 0, total DECIMAL(15,2) DEFAULT 0,
 amount_paid DECIMAL(15,2) DEFAULT 0, status VARCHAR(30) DEFAULT 'draft', due_at DATE NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CONSTRAINT fk_invoice_customer FOREIGN KEY(customer_id) REFERENCES customers(id), CONSTRAINT fk_invoice_subscription FOREIGN KEY(subscription_id) REFERENCES subscriptions(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS taxes (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(100) NOT NULL, rate DECIMAL(8,4) NOT NULL DEFAULT 0, country VARCHAR(80) NULL, status VARCHAR(20) DEFAULT 'active',
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS discounts (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(100) NOT NULL, code VARCHAR(80) NOT NULL UNIQUE, type VARCHAR(20) NOT NULL DEFAULT 'percentage',
 value DECIMAL(15,2) NOT NULL DEFAULT 0, valid_from DATE NULL, valid_until DATE NULL, status VARCHAR(20) DEFAULT 'active',
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS payments (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, reference VARCHAR(80) NOT NULL UNIQUE, customer_id INT UNSIGNED NOT NULL, invoice_id INT UNSIGNED NULL,
 amount DECIMAL(15,2) NOT NULL, method VARCHAR(30) DEFAULT 'bank_transfer', status VARCHAR(30) DEFAULT 'pending', paid_at DATETIME NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CONSTRAINT fk_payment_customer FOREIGN KEY(customer_id) REFERENCES customers(id), CONSTRAINT fk_payment_invoice FOREIGN KEY(invoice_id) REFERENCES invoices(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS refunds (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, payment_id INT UNSIGNED NOT NULL, amount DECIMAL(15,2) NOT NULL, reason TEXT NULL, status VARCHAR(30) DEFAULT 'pending',
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CONSTRAINT fk_refund_payment FOREIGN KEY(payment_id) REFERENCES payments(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS notifications (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id INT UNSIGNED NULL, title VARCHAR(160) NOT NULL, body TEXT NOT NULL, channel VARCHAR(30) DEFAULT 'in_app', read_at DATETIME NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CONSTRAINT fk_notification_user FOREIGN KEY(user_id) REFERENCES users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS settings (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, setting_key VARCHAR(120) NOT NULL UNIQUE, setting_value TEXT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;
